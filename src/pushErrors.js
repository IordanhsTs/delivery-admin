// ─── Γιατί υπάρχει αυτό ──────────────────────────────────────────────────────
// Το `supabase.functions.invoke` δεν λέει ΠΟΤΕ γιατί απέτυχε: για κάθε μη-2xx
// απάντηση δίνει ένα γενικό «non-2xx status code». Ο πραγματικός λόγος (403
// forbidden, 502 από το Firebase, 401 ληγμένο session) βρίσκεται στο σώμα της
// απάντησης, που κρέμεται στο `error.context` σαν Response.
//
// Χωρίς αυτό, κάθε αποτυχία ειδοποίησης έβγαζε το ίδιο αόριστο μήνυμα και ήταν
// αδύνατο να διαγνωστεί από τον διαχειριστή — ή από εμάς όταν το ανέφερε.

/**
 * Επιστρέφει ελληνικό, εκτελέσιμο λόγο αποτυχίας για ένα σφάλμα functions.invoke.
 * Δεν πετάει ποτέ: αν δεν μπορεί να διαβάσει το σώμα, γυρνά ό,τι ξέρει.
 */
export async function pushFailureReason(error) {
  const status = error?.context?.status;

  let body = null;
  try {
    body = await error.context?.json?.();
  } catch (_) {
    // Κενό ή μη-JSON σώμα — μένουμε στο status.
  }

  if (body?.reason) return body.reason;

  // Τα γνωστά σφάλματα των edge functions μας, σε γλώσσα που καταλαβαίνει ο χρήστης.
  // Το 401 της δικής μας function σημαίνει πάντα body.error === 'unauthorized' (ληγμένο
  // session). Αν το σώμα λέει κάτι ΑΛΛΟ (π.χ. απόρριψη σε επίπεδο gateway/apikey πριν
  // καν τρέξει ο κώδικάς μας), το δείχνουμε αυτούσιο αντί να το κρύψουμε πίσω από το
  // γενικό μήνυμα — αλλιώς δεν διαγνώσκεται ποτέ ένα 401 από διαφορετική αιτία.
  if (status === 401) {
    const detail = body?.error || body?.message;
    if (!detail || detail === 'unauthorized') {
      return 'Η σύνδεσή σας έληξε — κάντε ανανέωση της σελίδας και ξανασυνδεθείτε.';
    }
    return `Μη εξουσιοδοτημένο αίτημα: ${detail}. Αν επιμένει, ανανεώστε τη σελίδα.`;
  }
  if (status === 403) return 'Ο λογαριασμός σας δεν αναγνωρίζεται ως διαχειριστής από τον διακομιστή.';
  if (status === 404) return 'Η υπηρεσία ειδοποιήσεων δεν βρέθηκε σε αυτόν τον διακομιστή.';

  if (body?.error) return `${body.error}${status ? ` (κωδικός ${status})` : ''}`;
  if (status) return `Κωδικός σφάλματος ${status}.`;
  return 'Δεν υπήρξε απάντηση από τον διακομιστή — ελέγξτε τη σύνδεση.';
}
