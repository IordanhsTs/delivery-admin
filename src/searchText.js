// ── Σύγκριση ελληνικού κειμένου για αναζήτηση ───────────────────────────────
// Ο διαχειριστής ψάχνει βιαστικά, με το ένα χέρι, συχνά από κινητό: δεν πρέπει
// να χρειάζεται να πετύχει τόνο ή κεφαλαίο για να βρει τον διανομέα του.
//
// Το NFD σπάει κάθε τονισμένο γράμμα σε γράμμα + τόνο και το regex πετάει τους
// συνδυαστικούς τόνους. Το τελικό σίγμα μπαίνει χωριστά γιατί ΔΕΝ είναι θέμα
// τόνου: το «ς» και το «σ» είναι δύο διαφορετικοί χαρακτήρες, και κανείς δεν
// πληκτρολογεί τελικό σίγμα στη μέση μιας αναζήτησης.

/** «Παπαδόπουλος» → «παπαδοπουλοσ». Κενό/undefined γίνεται κενό κείμενο. */
export function norm(s) {
  return (s || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/ς/g, 'σ')
    .toLowerCase()
    .trim();
}

/** Ταιριάζει το `text` στο ερώτημα `q` (ήδη περασμένο από norm); */
export function matches(text, q) {
  return !q || norm(text).includes(q);
}
